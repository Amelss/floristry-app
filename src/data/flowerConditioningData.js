function scoreFlower(flower, query) {
  const q = query.toLowerCase().trim();
  const name = flower.name.toLowerCase();
  const allTerms = [name, ...(flower.aliases ?? [])];
  let best = 0;

  for (const term of allTerms) {
    if (term === q)           { best = Math.max(best, 100); break; }
    if (term.startsWith(q))  { best = Math.max(best, 80);  continue; }
    if (name.startsWith(q))  { best = Math.max(best, 75);  continue; }
    if (term.includes(q))    { best = Math.max(best, 60);  continue; }
    if (name.includes(q))    { best = Math.max(best, 55);  continue; }
    if (subsequence(term, q)){ best = Math.max(best, 30);  }
  }
  return best;
}

function subsequence(str, sub) {
  let si = 0;
  for (let i = 0; i < str.length && si < sub.length; i++) {
    if (str[i] === sub[si]) si++;
  }
  return si === sub.length && sub.length >= 3;
}

export function searchFlowers(query, excludeNames = []) {
  const q = query.trim();
  if (q.length < 2) return [];
  const excluded = new Set(excludeNames.map(n => n.toLowerCase()));

  return FLOWER_DB
    .filter(f => !excluded.has(f.name.toLowerCase()))
    .map(f => ({ ...f, _score: scoreFlower(f, q) }))
    .filter(f => f._score > 0)
    .sort((a, b) => b._score - a._score)
    .slice(0, 8);
}
